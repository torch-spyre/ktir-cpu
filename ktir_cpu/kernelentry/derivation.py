def read_sections(text: str) -> Dict[str, str]:
    """Every kernel's derivation in *text*, by kernel name."""
    return {m.group("name"): m.group("body") for m in _SECTION.finditer(text)}


def render_document(sections: Dict[str, str]) -> str:
    """The whole document, from a name -> derivation mapping.

    Ordered by name rather than by discovery, so adopting one kernel rewrites one
    section and a reordering never shows up as a diff.
    """
    parts = [TITLE, "", HEADER, "", PREAMBLE, ""]
    for name in sorted(sections):
        parts += [f"## {name}", "", "```text", sections[name], "```", ""]
    return "\n".join(parts).rstrip("\n") + "\n"


def update_document(path, name: str, body: str) -> bool:
    """Put *body* in as *name*'s section, leaving the others as committed.

    Returns whether anything changed.  Adopting one kernel must not depend on
    every other kernel having been run in the same invocation: the alternative is
    that a single-kernel ``adopt`` silently deletes seventeen sections.
    """
    existing = read_sections(path.read_text()) if path.exists() else {}
    if existing.get(name) == body:
        return False
    existing[name] = body
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_document(existing))
    return True


def _comm_by_op(report) -> List[Tuple[str, int, int]]:
    """Chip-wide cross-core bytes, by the op that moved them."""
    counts: Dict[str, int] = {}
    nbytes: Dict[str, int] = {}
    for counters in report.counters.values():
        for tentry in counters.trace or ():
            if tentry.category != "comm" or not tentry.nbytes:
                continue
            counts[tentry.op_type] = counts.get(tentry.op_type, 0) + 1
            nbytes[tentry.op_type] = nbytes.get(tentry.op_type, 0) + tentry.nbytes
    return sorted(((op, counts[op], nbytes[op]) for op in counts),
                  key=lambda row: (-row[2], row[0]))


def _per_op(report, core) -> List[Tuple[str, int, float]]:
    counts: Dict[str, int] = {}
    cycles: Dict[str, float] = {}
    for tentry in core.trace or ():
        counts[tentry.op_type] = counts.get(tentry.op_type, 0) + 1
        cycles[tentry.op_type] = cycles.get(tentry.op_type, 0.0) + tentry.cycles
    return sorted(((op, counts[op], cycles[op]) for op in counts),
                  key=lambda row: (-row[2], row[0]))
